export function translate(lang, key, replacements = {}) {
  const text = translations[lang]?.[key] || translations['en'][key] || key;
  return Object.entries(replacements).reduce(
    (acc, [key, value]) => acc.replace(`{${key}}`, value),
    text
  );
}
